#!/usr/bin/env node
/**
 * Local installer:
 *  1. writes the native-messaging host manifest for the chosen browser(s)
 *  2. makes the native-host wrapper executable
 *  3. prints the cordis.patch.yml row for dsh (and appends it with --write-dsh)
 *
 * Run `pnpm -w build` first.
 */
import { chmodSync, existsSync, mkdirSync, writeFileSync, readFileSync } from "node:fs";
import { homedir } from "node:os";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { extensionId } from "./ext-id.mjs";

const root = path.dirname(path.dirname(new URL(import.meta.url).pathname));
const args = process.argv.slice(2);
const writeDsh = args.includes("--write-dsh");
const browsersArg = args.find((a) => a.startsWith("--browsers="));
const browsers = browsersArg
  ? browsersArg.split("=")[1].split(",")
  : ["brave"];

const NATIVE_HOST_NAME = "com.dsh.browser_bridge";
const id = extensionId();

const NMH_DIRS = {
  brave: ".config/BraveSoftware/Brave-Browser/NativeMessagingHosts",
  chrome: ".config/google-chrome/NativeMessagingHosts",
  chromium: ".config/chromium/NativeMessagingHosts",
  "dsh-desktop": ".local/share/dsh-desktop/chromium/NativeMessagingHosts",
};

const wrapperPath = path.join(root, "packages/native-host/dsh-browser-bridge");
const mcpEntry = path.join(root, "packages/mcp-server/dist/index.js");
const nativeEntry = path.join(root, "packages/native-host/dist/index.js");

if (!existsSync(nativeEntry) || !existsSync(mcpEntry)) {
  console.error("Build output missing. Run `pnpm -w build` first.");
  process.exit(1);
}

// 1. wrapper script (native messaging `path` must be an executable)
const nodeBin = process.execPath;
writeFileSync(
  wrapperPath,
  `#!/bin/sh\n# Generated by scripts/install-local.mjs\nexec "${nodeBin}" "${nativeEntry}" "$@"\n`,
);
chmodSync(wrapperPath, 0o755);
console.log("wrapper:", wrapperPath);

// 2. native-messaging host manifest per browser
const manifest = {
  name: NATIVE_HOST_NAME,
  description: "DeepSeek Harness Browser Bridge",
  path: wrapperPath,
  type: "stdio",
  allowed_origins: [`chrome-extension://${id}/`],
};

for (const b of browsers) {
  const rel = NMH_DIRS[b];
  if (!rel) {
    console.warn(`unknown browser "${b}" — skipping`);
    continue;
  }
  const dir = path.join(homedir(), rel);
  mkdirSync(dir, { recursive: true });
  const file = path.join(dir, `${NATIVE_HOST_NAME}.json`);
  writeFileSync(file, JSON.stringify(manifest, null, 2) + "\n");
  console.log("native host manifest:", file);
}

console.log(`\nextension id: ${id}`);
console.log(`extension dir to load unpacked: ${path.join(root, "packages/extension/dist")}\n`);

// 3. cordis row for dsh — a new plugin is added via an `insert` patch entry
const row = `- insert:
    - id: mcp-browser
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: browser
        transport: stdio
        command: ${nodeBin}
        args:
          - ${mcpEntry}
        toolCallTimeoutMs: 120000
        reconnect:
          enabled: true
`;

const patchFile = path.join(homedir(), ".dsh/profiles/web/cordis.patch.yml");
console.log(`Add this row to ${patchFile}:\n`);
console.log(row);

if (writeDsh) {
  let current = "";
  try {
    current = readFileSync(patchFile, "utf8");
  } catch {
    current = "";
  }
  if (current.includes("id: mcp-browser")) {
    console.log("cordis.patch.yml already has an mcp-browser row — not touching it.");
  } else {
    // Keep comment lines, drop a lone `[]` empty-list marker, then append.
    const kept = current
      .split("\n")
      .filter((l) => l.trim() !== "[]")
      .join("\n")
      .replace(/\s*$/, "");
    const base = kept === "" ? "" : kept + "\n\n";
    writeFileSync(patchFile, base + row);
    console.log(`appended mcp-browser row to ${patchFile}`);
  }
}

console.log("\nNext:");
console.log("  1. Load the extension dir unpacked in your browser (developer mode).");
console.log("  2. Restart dsh (systemctl --user restart dsh-web.service) or run `dsh`.");
console.log("  3. Open the DSH Browser side panel — it should show Connected.");
